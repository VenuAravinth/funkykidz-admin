"use client";

import { useMemo, useState } from "react";
import Link from "next/link";
import { HiOutlinePrinter, HiOutlineSparkles } from "react-icons/hi2";
import { Input } from "@/components/atoms/Input";
import { IconButton } from "@/components/atoms/IconButton";
import { Table, TableHead, TableBody, TableRow, Th, Td, TableEmpty } from "@/components/atoms/Table";
import { formatDateTime } from "@/lib/format";
import { useAppSelector } from "@/stores/hooks";
import { selectProducts, selectVariants } from "@/stores/slices/catalogSlice";
import { selectBarcodeHistory } from "@/stores/slices/barcodeSlice";

export default function BarcodeHistoryPage() {
  const history = useAppSelector(selectBarcodeHistory);
  const products = useAppSelector(selectProducts);
  const variants = useAppSelector(selectVariants);

  const [query, setQuery] = useState("");

  const productById = useMemo(() => new Map(products.map((p) => [p.id, p])), [products]);
  const variantById = useMemo(() => new Map(variants.map((v) => [v.id, v])), [variants]);

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    return [...history]
      .sort((a, b) => (a.generatedAt < b.generatedAt ? 1 : -1))
      .filter((batch) => {
        if (!q) return true;
        const product = productById.get(batch.productId);
        return batch.barcode.toLowerCase().includes(q) || (product?.name.toLowerCase().includes(q) ?? false);
      });
  }, [history, query, productById]);

  return (
    <div>
      <div className="mb-5">
        <Input
          type="search"
          placeholder="Search by product or barcode…"
          value={query}
          onChange={(e) => setQuery(e.target.value)}
          className="max-w-sm"
        />
      </div>

      <Table stickyActions>
        <TableHead>
          <TableRow>
            <Th>Generated</Th>
            <Th>Product</Th>
            <Th>Variant</Th>
            <Th>Barcode</Th>
            <Th>Quantity</Th>
            <Th>Generated By</Th>
            <Th className="text-right">Actions</Th>
          </TableRow>
        </TableHead>
        <TableBody>
          {filtered.length === 0 && <TableEmpty colSpan={7} message="No barcode batches match your search." />}
          {filtered.map((batch) => {
            const product = productById.get(batch.productId);
            const variant = batch.variantId ? variantById.get(batch.variantId) : undefined;
            return (
              <TableRow key={batch.id}>
                <Td className="text-ink-muted">{formatDateTime(batch.generatedAt)}</Td>
                <Td className="font-medium text-ink">{product?.name ?? "—"}</Td>
                <Td>{variant ? `${variant.size} · ${variant.color}` : "—"}</Td>
                <Td className="text-ink-muted">{batch.barcode}</Td>
                <Td>{batch.quantity}</Td>
                <Td>{batch.generatedBy}</Td>
                <Td className="text-right">
                  <div className="flex justify-end gap-1">
                    <Link href={`/inventory/barcode-labels/print?batchId=${batch.id}`}>
                      <IconButton label={`Reprint labels for ${product?.name ?? batch.barcode}`}>
                        <HiOutlinePrinter className="h-4 w-4" />
                      </IconButton>
                    </Link>
                    <Link href={`/inventory/barcode-labels?barcode=${encodeURIComponent(batch.barcode)}`}>
                      <IconButton label={`Generate new labels for ${product?.name ?? batch.barcode}`}>
                        <HiOutlineSparkles className="h-4 w-4" />
                      </IconButton>
                    </Link>
                  </div>
                </Td>
              </TableRow>
            );
          })}
        </TableBody>
      </Table>
    </div>
  );
}
