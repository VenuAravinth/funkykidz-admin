export function onlineOrderTotal(order: OnlineOrder): number {
  return order.items.reduce((sum, item) => sum + item.quantity * item.price, 0);
}

export function getOnlineOrderById(id: string): OnlineOrder | undefined {
  return onlineOrders.find((o) => o.id === id);
}
